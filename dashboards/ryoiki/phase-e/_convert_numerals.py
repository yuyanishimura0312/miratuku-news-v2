# 1) 西暦4桁（漢数字混在含む）
YEAR_DIGITS = {'〇': '0', '一': '1', '二': '2', '三': '3', '四': '4', '五': '5', '六': '6', '七': '7', '八': '8', '九': '9'}

def convert_year(match):
    """漢数字4桁年号 → アラビア4桁"""
    s = match.group(0)
    digits = ''.join(YEAR_DIGITS.get(c, c) for c in s.replace('年', ''))
    return digits + '年'

